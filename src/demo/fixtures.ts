import type { FreeeRow, FreeeReport } from '../freee/types';

type V3 = [number, number, number];

function item(id: number, name: string, category: string, level: number, v: V3): FreeeRow {
  return {
    account_item_id: id,
    account_item_name: name,
    account_category_name: category,
    hierarchy_level: level,
    closing_balance: v[0],
    last_year_closing_balance: v[1],
    two_years_before_closing_balance: v[2],
  };
}
function total(category: string, level: number, parent: string | undefined, v: V3): FreeeRow {
  return {
    account_category_name: category,
    total_line: true,
    hierarchy_level: level,
    parent_account_category_name: parent,
    closing_balance: v[0],
    last_year_closing_balance: v[1],
    two_years_before_closing_balance: v[2],
  };
}
/** 単年度（通期）応答用。closing のみ持たせる */
function fyItem(id: number, name: string, category: string, level: number, v: number): FreeeRow {
  return { account_item_id: id, account_item_name: name, account_category_name: category, hierarchy_level: level, closing_balance: v };
}
function fyTotal(category: string, level: number, parent: string | undefined, v: number): FreeeRow {
  return { account_category_name: category, total_line: true, hierarchy_level: level, parent_account_category_name: parent, closing_balance: v };
}

